"""Generate magia_omp_entries.h from the .symtab of a MAGIA ELF.

The HERO clang names every "#pragma omp target" kernel

    __omp_offloading_<device id>_<file id>_<function>_l<line of the #pragma>

On a clang-compiled host the same names are in the host offloading table.
The RTEMS host is written by hand, so this script reads them from the
MAGIA ELF at build time and emits, for every function containing target
regions, its kernels in source order (sorted by #pragma line):

    #define MAGIA_OMP_<FUNCTION>_COUNT 3
    #define MAGIA_OMP_<FUNCTION>_0 "__omp_offloading_830_88efa_regions_l28"
    ...
    #define MAGIA_OMP_<FUNCTION>_NAMES { MAGIA_OMP_<FUNCTION>_0, ... }

_NAMES is an array initializer with all the names, in the same order, to
build the host offloading table for any number of regions.

The index (k-th #pragma omp target in the function) does not change when
lines are added or removed in the source file, unlike the line number.

Usage: gen_magia_omp_entries.py OUTPUT_HEADER [MAGIA_ELF]
Without MAGIA_ELF (or with an empty one) a header without kernels is written.
The output is rewritten only when its content changes.
"""

import os
import re
import struct
import sys

KERNEL_RE = re.compile(r"^__omp_offloading_([0-9a-f]+)_([0-9a-f]+)_(.+)_l([0-9]+)$")

SHT_SYMTAB = 2
STT_FUNC = 2
SHN_UNDEF = 0


class ElfError(Exception):
    pass


def read_symbols(data):
    """Yield (name, value, type, shndx) for every .symtab entry."""
    if len(data) < 16 or data[:4] != b"\x7fELF":
        raise ElfError("not an ELF file")
    if data[5] != 1:
        raise ElfError("only little-endian ELF files are supported")
    if data[4] == 1:                      # ELFCLASS32
        ehdr_fmt, shdr_fmt, sym_fmt = "<16sHHIIIIIHHHHHH", "<IIIIIIIIII", "<IIIBBH"
    elif data[4] == 2:                    # ELFCLASS64
        ehdr_fmt, shdr_fmt, sym_fmt = "<16sHHIQQQIHHHHHH", "<IIQQQQIIQQ", "<IBBHQQ"
    else:
        raise ElfError("unsupported ELF class")

    if len(data) < struct.calcsize(ehdr_fmt):
        raise ElfError("truncated ELF header")
    ehdr = struct.unpack_from(ehdr_fmt, data)
    shoff, shentsize, shnum = ehdr[6], ehdr[11], ehdr[12]
    if shentsize != struct.calcsize(shdr_fmt):
        raise ElfError("unexpected section header size")

    def shdr(i):
        off = shoff + i * shentsize
        if off + shentsize > len(data):
            raise ElfError("section header table exceeds file size")
        s = struct.unpack_from(shdr_fmt, data, off)
        # (type, offset, size, link, entsize), independent of the class
        return s[1], s[4], s[5], s[6], s[9]

    for i in range(shnum):
        sh_type, sh_offset, sh_size, sh_link, sh_entsize = shdr(i)
        if sh_type != SHT_SYMTAB:
            continue
        if sh_entsize != struct.calcsize(sym_fmt):
            raise ElfError("unexpected symbol size")
        _, str_off, str_size, _, _ = shdr(sh_link)
        if sh_offset + sh_size > len(data) or str_off + str_size > len(data):
            raise ElfError(".symtab or .strtab exceeds file size")
        strtab = data[str_off:str_off + str_size]
        for off in range(sh_offset, sh_offset + sh_size, sh_entsize):
            sym = struct.unpack_from(sym_fmt, data, off)
            if data[4] == 1:
                st_name, st_value, _, st_info, _, st_shndx = sym
            else:
                st_name, st_info, _, st_shndx, st_value, _ = sym
            end = strtab.find(b"\0", st_name)
            name = strtab[st_name:end if end >= 0 else None].decode("ascii", "replace")
            yield name, st_value, st_info & 0xf, st_shndx
        return
    raise ElfError("no .symtab (MAGIA ELF stripped?)")


def collect_kernels(data):
    """Return {function: [(line, name, address), ...]} sorted by line."""
    kernels = {}
    files = {}
    for name, value, sym_type, shndx in read_symbols(data):
        m = KERNEL_RE.match(name)
        if not m or sym_type != STT_FUNC or shndx == SHN_UNDEF:
            continue
        file_id, func, line = m.group(2), m.group(3), int(m.group(4))
        # the same function name in two source files would mix their regions
        if files.setdefault(func, file_id) != file_id:
            raise ElfError("function '%s' has target regions in more than one "
                           "file (file ids %s, %s)" % (func, files[func], file_id))
        kernels.setdefault(func, []).append((line, name, value))
    for func in kernels:
        kernels[func].sort()
    return kernels


def c_ident(func):
    return re.sub(r"[^0-9A-Za-z]", "_", func).upper()


def render(elf_path, kernels):
    out = [
        "/* SPDX-License-Identifier: BSD-2-Clause */",
        "",
        "/*",
        " * GENERATED by gen_magia_omp_entries.py - DO NOT EDIT.",
        " * Source: %s" % (elf_path or "(no MAGIA ELF)"),
        " *",
        " * OpenMP target regions of the MAGIA ELF, per function, in source order:",
        " * MAGIA_OMP_<FUNCTION>_<k> is the full name of the k-th",
        " * \"#pragma omp target\" of <FUNCTION> (k counts from 0);",
        " * MAGIA_OMP_<FUNCTION>_NAMES initializes an array with all of them.",
        " */",
        "",
        "#ifndef MAGIA_OMP_ENTRIES_H",
        "#define MAGIA_OMP_ENTRIES_H",
        "",
    ]
    total = 0
    for func in sorted(kernels):
        ident = c_ident(func)
        out.append("/* %s() */" % func)
        out.append("#define MAGIA_OMP_%s_COUNT %d" % (ident, len(kernels[func])))
        for k, (line, name, value) in enumerate(kernels[func]):
            out.append('#define MAGIA_OMP_%s_%d "%s" /* line %d, 0x%08x */'
                       % (ident, k, name, line, value))
        out.append("#define MAGIA_OMP_%s_NAMES { \\" % ident)
        for k in range(len(kernels[func])):
            out.append("    MAGIA_OMP_%s_%d, \\" % (ident, k))
        out.append("}")
        out.append("")
        total += len(kernels[func])
    out.append("#define MAGIA_OMP_NUM_ENTRIES %d" % total)
    out.append("")
    out.append("#endif /* MAGIA_OMP_ENTRIES_H */")
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) not in (2, 3):
        sys.stderr.write("usage: %s OUTPUT_HEADER [MAGIA_ELF]\n" % argv[0])
        return 2
    out_path = argv[1]
    elf_path = argv[2] if len(argv) == 3 else ""

    kernels = {}
    if elf_path:
        try:
            with open(elf_path, "rb") as f:
                kernels = collect_kernels(f.read())
        except (OSError, ElfError) as e:
            sys.stderr.write("gen_magia_omp_entries: %s: %s\n" % (elf_path, e))
            return 1

    text = render(elf_path, kernels)
    try:
        with open(out_path) as f:
            if f.read() == text:
                return 0                      # unchanged: no rebuild
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w") as f:
        f.write(text)
    for func in sorted(kernels):
        print("[OMP  ] %s(): %d target regions" % (func, len(kernels[func])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
