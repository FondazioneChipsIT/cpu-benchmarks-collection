const char rtems_test_name[] = "OMP OFFLOAD";

/*
 * GVSoC maps the MAGIA L2 (0xC000_0000) on the part of the QEMU RAM seen at
 * 0xC000_0000 (UMA), so RTEMS and MAGIA use the same addresses
 * (offload_layout.h). Outside the RTEMS RAM region: requires a QEMU RAM
 * covering it (e.g. -m 2G).
 */

/* MAGIA ELF embedded in the image by magia_elf.c (.incbin) */
extern const unsigned char magia_elf[];
extern const size_t magia_elf_size;

// ===========================================================================
// PART 1 - the kernels were generated by the HERO clang (kernels_omp.o, the
// omp_hero_kernels() chain in omp/hero_magia.cmake): one per #pragma omp target,
// named "__omp_offloading_<id>_regions_l<line of the #pragma>".
//
// Host and device are two separate ELFs: the RTEMS ELF has no
// omp_offloading_entries table, so the wrapper addresses are read from the
// symbol table (.symtab) of the embedded MAGIA ELF, as the HERO plugin does
// in satisfy_requested_symbols (plugins/hero/rtl.cpp:106).
// Difference: in HERO the full names come from the host table generated by
// clang; here the host is not compiled by the HERO clang, so we search by suffix.
// ===========================================================================

// Regions are identified by the line of the #pragma in src/kernels_omp.c
// (the rest of the name depends on the file and changes if it is regenerated).
// WARNING: if lines are added or removed above the #pragmas in kernels_omp.c,
// these numbers must be updated (the test prints the kernels found in the ELF).
#define KERNEL_NOP_SUFFIX        "_l28"
#define KERNEL_MAP_TO_SUFFIX     "_l32"
#define KERNEL_MAP_TOFROM_SUFFIX "_l36"

// In HERO: satisfy_requested_symbols (rtl.cpp). Finds the addresses of the
// wrapper functions, one per #pragma omp target.
// As in HERO it is all or nothing: returns 0 only if all kernels are
// resolved, otherwise -1 (HERO returns false and __tgt_rtl_load_binary NULL).
// It looks them all up anyway, so that every missing one gets reported.
static int resolve_kernels(kernel_t *nop, kernel_t *map_to, kernel_t *map_tofrom)
{
    printf("[host] OpenMP kernels in the MAGIA .symtab:\n");
    if (magia_elf_foreach_symbol(magia_elf, magia_elf_size,
                                 print_omp_kernel, NULL) < 0) {
        // In HERO: "Symbols section not found" -> return false
        printf("[host]   no .symtab (MAGIA ELF stripped?)\n");
        return -1;
    }
    *nop        = find_kernel(magia_elf, magia_elf_size, KERNEL_NOP_SUFFIX);
    *map_to     = find_kernel(magia_elf, magia_elf_size, KERNEL_MAP_TO_SUFFIX);
    *map_tofrom = find_kernel(magia_elf, magia_elf_size, KERNEL_MAP_TOFROM_SUFFIX);

    if (*nop == NULL || *map_to == NULL || *map_tofrom == NULL)
        return -1;
    return 0;
}

// ===========================================================================
// PART 2 - what libomptarget + the HERO plugin do (host side) is in the
// libopenmpplugin (device init/stop, data alloc/submit/retrieve, target
// regions) and libmagiamailbox (mailboxes and "ready" cell) static libraries.
// ===========================================================================

// Maximum wait for each mailbox word, passed to the libopenmpplugin API.
// GVSoC simulates MAGIA much more slowly than QEMU's real time: a passing test
// still takes ~3 s. Can be overridden via cflags.
#ifndef OFL_MBOX_TIMEOUT_MS
#define OFL_MBOX_TIMEOUT_MS 30000u
#endif

// ---------------------------------------------------------------------------
// The "host program": regions() from kernels_omp.c, written by hand.
// Riccardo: on the real host these calls are generated by clang from the #pragmas
// of the host part of kernels_omp.c and executed by libomptarget (alloc, submit of
// "to", run, retrieve of "from", delete), one region at a time.
// ---------------------------------------------------------------------------
static kernel_t k_nop, k_map_to, k_map_tofrom;

static int regions(void)
{
    uint32_t tmp_1 = 5;
    uint32_t tmp_2 = 10;

    // #pragma omp target  { nop }           ("enter_omp_init")
    if (run_target_region(k_nop, 0, NULL, OFL_MBOX_TIMEOUT_MS))
        return -1;

    // #pragma omp target  { nop }           ("enter_omp_nop")
    if (run_target_region(k_nop, 0, NULL, OFL_MBOX_TIMEOUT_MS))
        return -1;

    // #pragma omp target map(to: tmp_1)
    {
        uintptr_t p1 = data_alloc(sizeof tmp_1);
        data_submit(p1, &tmp_1, sizeof tmp_1);              // "to": copy into L2
        if (run_target_region(k_map_to, 1, &p1, OFL_MBOX_TIMEOUT_MS))
            return -1;
        // "to" does not copy back; data_delete: the allocator does not free
    }

    // #pragma omp target map(tofrom: tmp_1, tmp_2)  { tmp_1 = tmp_2; }
    {
        uintptr_t ptrs[2] = { data_alloc(sizeof tmp_1), data_alloc(sizeof tmp_2) };
        data_submit(ptrs[0], &tmp_1, sizeof tmp_1);
        data_submit(ptrs[1], &tmp_2, sizeof tmp_2);
        if (run_target_region(k_map_tofrom, 2, ptrs, OFL_MBOX_TIMEOUT_MS))
            return -1;
        data_retrieve(&tmp_1, ptrs[0], sizeof tmp_1);       // "from": copy back to the host
        data_retrieve(&tmp_2, ptrs[1], sizeof tmp_2);
    }

    if (tmp_1 != tmp_2 || tmp_1 != 10) {
        printf("[host] FAIL: map tofrom, tmp_1 = %" PRIu32 ", tmp_2 = %" PRIu32 "\n",
               tmp_1, tmp_2);
        return -1;
    }
    return 0;
}

static rtems_task Init( rtems_task_argument ignored )
{
  elf_info_t elf_info;
  int errors = 0;

  (void) ignored;

  TEST_BEGIN();

  /*
   * As in HERO __tgt_rtl_load_binary: resolve the kernels first, on the
   * embedded ELF image, and fail the load if any is missing. The ELF is not
   * loaded and MAGIA is never started (no fetch enable, so no STOP needed).
   */
  if ( resolve_kernels( &k_nop, &k_map_to, &k_map_tofrom ) != 0 ) {
    /* no TEST_END(): "*** END OF TEST" means success for the RTEMS tester */
    printf( "[host] FAIL: MAGIA ELF load aborted, missing kernels\n" );
    printf( "[host] TEST FAIL\n" );
    rtems_test_exit( 1 );
  }

  memset( &elf_info, 0, sizeof( elf_info ) );
  load_elf_from_memory( magia_elf, magia_elf_size, &elf_info );

  /*
   * Mailboxes and "ready" cell first, MAGIA fetch enable last (contract in
   * offload_layout.h): MAGIA starts only with the shared memory already set
   * up and cannot see a stale ready flag left by a previous run.
   */
  magia_dev_init();
  set_entry_point_and_enable_fetch( &elf_info );

  /* Execute offloaded regions */
  if ( errors == 0 && regions() != 0 ) {
    errors = 1;
  }

  /* Always STOP, also on failure, so that MAGIA leaves and GVSoC ends */
  magia_dev_stop( OFL_MBOX_TIMEOUT_MS );

  if ( errors != 0 ) {
    /* no TEST_END(): "*** END OF TEST" means success for the RTEMS tester */
    printf( "[host] TEST FAIL\n" );
    rtems_test_exit( 1 );
  }

  printf( "[host] TEST PASS\n" );
  TEST_END();
  rtems_test_exit( 0 );
}

